const FIXTURE = eval("[" + arrSrc + "]").join(NL);
const idx = FIXTURE.indexOf("failing tests:");
const section = FIXTURE.slice(idx);
const entryRe = /^test at (.+)$/gm;
const starts = [];
let mm;
while ((mm = entryRe.exec(section)) !== null) starts.push({ file: mm[1], at: mm.index + mm[0].length });
console.log("entries:", starts.length);
const last = starts[starts.length - 1];
const block = section.slice(last.at, section.indexOf("test at", last.at) >= 0 ? section.indexOf("test at", last.at) : undefined);
